    private void jbInscribirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbInscribirActionPerformed
        int filaSeleccionada = jtMaterias.getSelectedRow();
        
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(null, "Por favor seleccione una Materia de la tabla");
            return;
        }
        
        Alumno alumnoSeleccionado = (Alumno) jcbAlumno.getSelectedItem();
        if (alumnoSeleccionado ==null) {
            JOptionPane.showMessageDialog(null, "Por favor seleccione un Alumno");
            return;
        }
        MateriaData materiaData = new MateriaData();
        int idMateria = (Integer) jtMaterias.getValueAt(filaSeleccionada, 0);
        Materia materiaSeleccionada = materiaData.buscarMateria(idMateria);
        Inscripcion inscripcion = new Inscripcion(alumnoSeleccionado,materiaSeleccionada);
        inscripcionData.guardarInscripcion(inscripcion);
        
        
    }//GEN-LAST:event_jbInscribirActionPerformed

