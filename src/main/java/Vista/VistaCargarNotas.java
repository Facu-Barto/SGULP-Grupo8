    private void cargarAlumnos() {
        cboxAlumnos.removeAllItems();
        List<Alumno> lista = alumnoData.listarAlumnos();

        for (Alumno a : lista) {
            cboxAlumnos.addItem(a);
        }
    }
    
    private void cargarTablaMaterias(int idAlumno) {
        modeloTabla.setRowCount(0);
        List<Inscripcion> lista = inscripcionData.obtenerInscripcionesPorAlumno(idAlumno);
        
        for (Inscripcion insc : lista) {
            modeloTabla.addRow(new Object[]{
                insc.getId_cursada(),
                insc.getId_materia().getNombre(),
                insc.getCursa(),
                insc.getNota(),
                insc.getAsistencia()
            });
        }
    }
    
