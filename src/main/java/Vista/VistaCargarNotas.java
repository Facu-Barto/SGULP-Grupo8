    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        int filaSeleccionada = tableMaterias.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this,"Debe seleccionar una materia de la tabla.","Ninguna fila seleccionada",JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idCursada = (int) tableMaterias.getValueAt(filaSeleccionada,0);
            //Leemos lo que el usuario ingresa en las celdas de nota y asistencia.
            Object notaObj = tableMaterias.getValueAt(filaSeleccionada,3);
            Object asistenciaObj = tableMaterias.getValueAt(filaSeleccionada,4);

            if (notaObj == null || asistenciaObj == null || notaObj.toString().isEmpty() || asistenciaObj.toString().isEmpty()) {
                JOptionPane.showMessageDialog(this,"La nota y la asistencia no pueden estar vacías.","Campos Vacíos",JOptionPane.WARNING_MESSAGE);
                return;
            }

            double nota = Double.parseDouble(notaObj.toString());
            int asistencia = Integer.parseInt(asistenciaObj.toString());

            if (nota<0 || nota>10) {
                JOptionPane.showMessageDialog(this,"La nota debe estar entre 0 y 10.","Error de Rango",JOptionPane.ERROR_MESSAGE);
                return;
            }

            inscripcionData.actualizarNota(idCursada, nota, asistencia);
            //Recargamos la tabla del alumno especifico
            Alumno seleccionado = (Alumno) cboxAlumnos.getSelectedItem();
            
            if (seleccionado != null) {
                cargarTablaMaterias(seleccionado.getId_alumno());
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this,"Ingrese numeros válidos para la nota y la asistencia.","Error de Formato",JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

